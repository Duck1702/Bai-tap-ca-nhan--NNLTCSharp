IF OBJECT_ID('CHITIET_HOADON') IS NOT NULL DROP TABLE CHITIET_HOADON;
IF OBJECT_ID('HOADON') IS NOT NULL DROP TABLE HOADON;
IF OBJECT_ID('TONKHO') IS NOT NULL DROP TABLE TONKHO;
IF OBJECT_ID('SANPHAM') IS NOT NULL DROP TABLE SANPHAM;
GO

-- Kiểu dữ liệu dưới đây được chọn để hiện thực theo sơ đồ trong tài liệu.
CREATE TABLE SANPHAM(
    MaSP INT IDENTITY(1,1) PRIMARY KEY,
    TenSP NVARCHAR(150) NOT NULL
);

CREATE TABLE TONKHO(
    MaSP INT NOT NULL REFERENCES SANPHAM(MaSP),
    NgayTon DATE NOT NULL,
    SLDau INT NOT NULL DEFAULT 0,
    SLNhap INT NOT NULL DEFAULT 0,
    SLBan INT NOT NULL DEFAULT 0,
    CONSTRAINT PK_TONKHO PRIMARY KEY(MaSP,NgayTon),
    CONSTRAINT CK_TONKHO_NONNEG CHECK(SLDau>=0 AND SLNhap>=0 AND SLBan>=0)
);

CREATE TABLE HOADON(
    MaHD INT IDENTITY(1,1) PRIMARY KEY,
    NgayTao DATETIME NOT NULL DEFAULT GETDATE(),
    TinhTrangThanhToan BIT NOT NULL DEFAULT 0
);

CREATE TABLE CHITIET_HOADON(
    MaHD INT NOT NULL REFERENCES HOADON(MaHD),
    MaSP INT NOT NULL REFERENCES SANPHAM(MaSP),
    SoLuong INT NOT NULL CHECK(SoLuong>0),
    CONSTRAINT PK_CHITIET_HOADON PRIMARY KEY(MaHD,MaSP)
);

